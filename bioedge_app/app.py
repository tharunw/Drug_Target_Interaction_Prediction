@st.cache_data
def load_chunks():
    text = README_PATH.read_text(encoding="utf-8") if README_PATH.exists() else (
        "Project README.md was not found. Put the original README.md in the repository root."
    )
    parts = re.split(r"\n(?=#+ )|\n\s*\n", text)
    chunks = [p.strip() for p in parts if len(p.strip()) > 80]
    return chunks or [text]

chunks = load_chunks()
vectorizer = TfidfVectorizer(stop_words="english", ngram_range=(1, 2), max_features=12000)
matrix = vectorizer.fit_transform(chunks)

def retrieve(question, k=3):
    qv = vectorizer.transform([question])
    scores = cosine_similarity(qv, matrix).ravel()
    ids = scores.argsort()[::-1][:k]
    return [(chunks[i], float(scores[i])) for i in ids if scores[i] > 0]

def ask_ollama(question, context, model):
    prompt = (
        "You are BioEdge AI, a biomedical research assistant. Answer only from the "
        "provided project context. If the context does not contain the answer, say so. "
        "Do not provide medical advice or claim clinical validation.\n\n"
        f"CONTEXT:\n{context}\n\nQUESTION: {question}"
    )
    response = requests.post(
        "http://localhost:11434/api/generate",
        json={"model": model, "prompt": prompt, "stream": False},
        timeout=75,
    )
    response.raise_for_status()
    return response.json().get("response", "")

chat_tab, insights_tab, about_tab = st.tabs(
    ["💬 Research Assistant", "📊 Model Insights", "ℹ️ About"]
)

with chat_tab:
    st.subheader("Ask questions about the DTI project")
    st.caption("Retrieval searches your README locally. Optional generation uses an already-installed local Ollama model.")
    use_ollama = st.toggle("Use local Ollama model (optional)", value=False)
    model = st.text_input("Ollama model name", "llama3.2:1b", disabled=not use_ollama)
    question = st.text_area(
        "Your research question",
        placeholder="Why does protein-grouped evaluation perform worse than random split?",
        height=90,
    )
    if st.button("Find answer", type="primary", disabled=not question.strip()):
        matches = retrieve(question)
        if not matches:
            st.warning("No relevant README passage was found. Try a more specific question.")
        else:
            context = "\n\n".join(item[0] for item in matches)
            if use_ollama:
                try:
                    with st.spinner("Generating with your local model..."):
                        answer = ask_ollama(question, context, model)
                    st.markdown("### BioEdge AI response")
                    st.write(answer)
                    st.caption("Generated by the local Ollama service using retrieved project context.")
                except Exception as exc:
                    st.error(f"Local model unavailable: {exc}")
                    st.info("Disable Ollama mode to view retrieved evidence without a generative model.")
            else:
                st.markdown("### Retrieved project evidence")
                st.write("Retrieval-only mode returns matching source passages rather than inventing a generated answer.")
                for index, (passage, score) in enumerate(matches, 1):
                    with st.expander(f"Evidence {index} · relevance {score:.2f}", expanded=index == 1):
                        st.markdown(passage)
                st.caption("Source: README.md, indexed locally on this computer.")

    with st.expander("Example questions"):
        st.write("- What features are used in the enhanced model?")
        st.write("- How many protein targets are in the dataset?")
        st.write("- What does negative protein-grouped R² indicate?")

